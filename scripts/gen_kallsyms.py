#!/usr/bin/env python3
"""
Turn the bare-linked kernel image into a built-in kallsyms table source.

Runs `nm -n --defined-only` on one ELF, keeps the code symbols (type T/t,
skipping linker-generated ".label" markers), and writes a C++ translation
unit defining `kBuiltInKallsyms` for kernel/debug/kallsyms.cpp.

The output file is only rewritten when its content actually changes, so an
unchanged image does not restamp the source and does not re-trigger the
final link on every rebuild.
"""

import argparse
import os
import subprocess
import sys

PROLOG = """// generated by scripts/gen_kallsyms.py from {origin} -- do not edit
#include "kernel/debug/kallsyms.hpp"

extern "C" {{
extern const cinux::debug::KallsymEntry kBuiltInKallsyms[] \\
    __attribute__((section(".rodata.kallsyms"))) = {{
"""

EPILOG = """}};

extern const unsigned long long kBuiltInKallsymsCount
    __attribute__((section(".rodata.kallsyms"))) = {count};
}}
"""


def kept_symbols(nm_path, image_path):
    listing = subprocess.run(
        [nm_path, "-n", "--defined-only", image_path],
        check=True, capture_output=True, text=True).stdout
    kept, seen_addresses = [], set()
    for line in listing.splitlines():
        fields = line.split(maxsplit=2)
        if len(fields) != 3:
            continue
        address, symbol_type, name = fields
        if symbol_type not in "Tt" or name.startswith("."):
            continue
        if address in seen_addresses:
            continue
        seen_addresses.add(address)
        kept.append((int(address, 16), name))
    for (previous, _), (current, _) in zip(kept, kept[1:]):
        if current <= previous:
            raise SystemExit(
                f"{image_path}: nm listing is not strictly ascending "
                f"at 0x{current:x}; the lookup binary search needs an ordered table"
            )
    return kept


def cpp_string(name):
    return name.replace("\\", "\\\\").replace('"', '\\"')


def rendered(kept, origin):
    lines = [PROLOG.format(origin=origin)]
    lines += ['    {{0x{:x}ULL, "{}"}},\n'.format(addr, cpp_string(name))
              for addr, name in kept]
    lines.append(EPILOG.format(count=len(kept)))
    return "".join(lines)


def write_when_changed(path, content):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as current:
            if current.read() == content:
                return
    with open(path, "w", encoding="utf-8") as target:
        target.write(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nm", required=True, help="path to the nm tool")
    parser.add_argument("--output", required=True, help="generated source path")
    parser.add_argument("image", help="bare-linked ELF to read symbols from")
    args = parser.parse_args()

    kept = kept_symbols(args.nm, args.image)
    write_when_changed(args.output, rendered(kept, os.path.basename(args.image)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
